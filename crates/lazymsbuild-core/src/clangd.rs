//! clangd: the `.clangd` lazymsbuild generates, finding clangd, and `clangd --check`.

use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::LazyLock;

use anyhow::{Context, Result};
use regex::Regex;

use crate::{fsutil, paths};

pub const FILE_NAME: &str = ".clangd";

/// Flags clangd must drop from MSVC compile commands: MSVC's precompiled headers, which clang
/// cannot read.
pub const REQUIRED_REMOVE: [&str; 3] = ["/Yu*", "/Yc*", "/Fp*"];

/// The first line of a `.clangd` lazymsbuild wrote.
pub const GENERATED_MARK: &str = "# Generated by lazymsbuild.";

/// The `.clangd` `init` writes when there is none.
pub fn default_file() -> String {
    format!(
        "{GENERATED_MARK} Safe to edit or commit.\nCompileFlags:\n  Remove: [{}]   # MSVC precompiled headers: clang cannot read them\n",
        REQUIRED_REMOVE.join(", ")
    )
}

/// What an existing `.clangd` lacks.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct FileCheck {
    pub exists: bool,
    pub generated: bool,
    /// Entries of [`REQUIRED_REMOVE`] not found in any `Remove` list.
    pub missing: Vec<&'static str>,
}

/// Looks for the `Remove` entries in a clangd configuration file. This reads YAML only as far
/// as needed: an entry counts when it appears in a `Remove:` list (flow `[a, b]` or block `- a`),
/// written with `/` or `-`.
pub fn inspect(path: &Path) -> FileCheck {
    let Ok(text) = crate::text::read_text(path) else {
        return FileCheck { missing: REQUIRED_REMOVE.to_vec(), ..Default::default() };
    };
    let removed = remove_entries(&text);
    let missing = REQUIRED_REMOVE
        .iter()
        .copied()
        .filter(|wanted| {
            let bare = wanted.trim_start_matches('/').trim_end_matches('*');
            !removed.iter().any(|r| {
                let r = r.trim_matches(['\'', '"']).trim_start_matches(['/', '-']);
                r.trim_end_matches('*') == bare || r == format!("{bare}*")
            })
        })
        .collect();
    FileCheck { exists: true, generated: text.starts_with(GENERATED_MARK), missing }
}

fn remove_entries(text: &str) -> Vec<String> {
    let mut entries = Vec::new();
    let mut in_block: Option<usize> = None;
    for line in crate::text::lines(text) {
        let without_comment = line.split(" #").next().unwrap_or(line);
        let indent = without_comment.len() - without_comment.trim_start().len();
        let trimmed = without_comment.trim();
        if let Some(block_indent) = in_block {
            if let Some(item) = trimmed.strip_prefix("- ") {
                entries.push(item.trim().to_string());
                continue;
            }
            if !trimmed.is_empty() && indent <= block_indent {
                in_block = None;
            }
        }
        if let Some(rest) = trimmed.strip_prefix("Remove:") {
            let rest = rest.trim();
            if let Some(list) = rest.strip_prefix('[') {
                let list = list.trim_end_matches(']');
                entries.extend(list.split(',').map(|s| s.trim().to_string()).filter(|s| !s.is_empty()));
            } else if rest.is_empty() {
                in_block = Some(indent);
            } else {
                entries.push(rest.to_string());
            }
        }
    }
    entries
}

/// What to add to an existing `.clangd` that lacks entries.
pub fn suggestion(missing: &[&str]) -> String {
    format!("CompileFlags:\n  Remove: [{}]\n", missing.join(", "))
}

/// For external mode: the block to add to clangd's user configuration
/// (`%LOCALAPPDATA%\clangd\config.yaml`), limited to this repository with `If: PathMatch`.
pub fn user_config_block(root: &Path) -> String {
    let pattern = regex::escape(&root.to_string_lossy().replace('\\', "/"));
    format!("---\nIf:\n  PathMatch: {pattern}/.*\nCompileFlags:\n  Remove: [{}]\n", REQUIRED_REMOVE.join(", "))
}

/// clangd's user configuration file.
pub fn user_config_path() -> Option<PathBuf> {
    dirs::data_local_dir().map(|d| d.join("clangd").join("config.yaml"))
}

/// Finds clangd: the configured path, `PATH`, Mason (Neovim), Visual Studio's LLVM, the VS Code
/// clangd extension. Returns the path and where it was found.
pub fn find(configured: Option<&Path>) -> Option<(PathBuf, &'static str)> {
    if let Some(path) = configured {
        return path.is_file().then(|| (path.to_path_buf(), "configuration"));
    }
    if let Some(found) = fsutil::which("clangd.exe") {
        return Some((found, "PATH"));
    }
    let local = dirs::data_local_dir();
    if let Some(found) =
        local.as_ref().and_then(|l| newest_match(&l.join(r"nvim-data\mason\packages\clangd"), r"*\bin\clangd.exe"))
    {
        return Some((found, "Mason"));
    }
    if let Ok(instances) = crate::msbuild::locate::instances() {
        for instance in instances {
            for arch in ["x64", "ARM64"] {
                let candidate = instance.path.join(format!(r"VC\Tools\Llvm\{arch}\bin\clangd.exe"));
                if candidate.is_file() {
                    return Some((candidate, "Visual Studio"));
                }
            }
        }
    }
    if let Some(found) = dirs::config_dir().and_then(|c| {
        newest_match(
            &c.join(r"Code\User\globalStorage\llvm-vs-code-extensions.vscode-clangd\install"),
            r"*\*\bin\clangd.exe",
        )
    }) {
        return Some((found, "VS Code"));
    }
    None
}

fn newest_match(dir: &Path, pattern: &str) -> Option<PathBuf> {
    let full = dir.join(pattern);
    let mut found: Vec<PathBuf> = glob::glob(&full.to_string_lossy()).ok()?.filter_map(|p| p.ok()).collect();
    found.sort();
    found.pop()
}

fn command(exe: &Path) -> Command {
    let mut cmd = Command::new(exe);
    cmd.stdin(Stdio::null());
    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        cmd.creation_flags(0x0800_0000); // CREATE_NO_WINDOW
    }
    cmd
}

/// `clangd --version`, first line.
pub fn version(exe: &Path) -> Result<String> {
    let output = command(exe).arg("--version").output().with_context(|| format!("cannot run {}", exe.display()))?;
    let text = String::from_utf8_lossy(&output.stdout);
    Ok(text.lines().next().unwrap_or_default().trim().to_string())
}

/// The result of `clangd --check=<file>`.
#[derive(Clone, Debug)]
pub struct CheckResult {
    pub file: PathBuf,
    /// From "All checks completed, N errors". `None` when clangd did not get that far.
    pub errors: Option<usize>,
    /// The diagnostics clangd reported (`[code] Line N: message`).
    pub diagnostics: Vec<String>,
    /// The compile command clangd used came from the database (not a fallback).
    pub from_database: bool,
}

static ALL_CHECKS: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"All checks completed, (\d+) errors?").unwrap());
static DIAGNOSTIC: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"\] (\[[^\]]+\] )?Line \d+:.*$").unwrap());

/// Runs `clangd --check` on one file, with `--compile-commands-dir` in external mode.
pub fn check_file(exe: &Path, file: &Path, compile_commands_dir: Option<&Path>) -> Result<CheckResult> {
    let mut cmd = command(exe);
    cmd.arg(format!("--check={}", file.display()));
    if let Some(dir) = compile_commands_dir {
        cmd.arg(format!("--compile-commands-dir={}", dir.display()));
    }
    cmd.current_dir(file.parent().unwrap_or(Path::new(".")));
    let output = cmd.output().with_context(|| format!("cannot run {}", exe.display()))?;
    // clangd logs to stderr.
    let text = format!("{}{}", String::from_utf8_lossy(&output.stderr), String::from_utf8_lossy(&output.stdout));
    let errors = ALL_CHECKS.captures(&text).and_then(|c| c[1].parse().ok());
    let diagnostics = text
        .lines()
        .filter_map(|l| DIAGNOSTIC.find(l).map(|m| m.as_str().trim_start_matches("] ").to_string()))
        .collect();
    let from_database = text.contains("Compile command from CDB is");
    Ok(CheckResult { file: paths::normalize(file), errors, diagnostics, from_database })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn check(text: &str) -> FileCheck {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join(FILE_NAME);
        std::fs::write(&path, text).unwrap();
        inspect(&path)
    }

    #[test]
    fn the_generated_file_is_complete() {
        let c = check(&default_file());
        assert_eq!(c, FileCheck { exists: true, generated: true, missing: Vec::new() });
    }

    #[test]
    fn finds_entries_in_flow_and_block_lists() {
        assert!(check("CompileFlags:\n  Remove: [-Yu*, \"/Yc*\", /Fp*]\n").missing.is_empty());
        assert!(
            check("CompileFlags:\n  Remove:\n    - /Yu*\n    - /Yc*\n    - /Fp*\n  Add: [-Wall]\n").missing.is_empty()
        );
        assert_eq!(check("CompileFlags:\n  Add: [-DX]\n").missing, REQUIRED_REMOVE);
        assert_eq!(check("CompileFlags:\n  Remove: [/Yu*]\n").missing, ["/Yc*", "/Fp*"]);
        assert!(!check("CompileFlags:\n  Remove: [/Yu*]\n").generated);
    }

    #[test]
    fn user_config_block_matches_the_repository() {
        let block = user_config_block(Path::new(r"C:\work\repo"));
        assert!(block.contains(r"PathMatch: C:/work/repo/.*"), "{block}");
        assert!(block.contains("Remove: [/Yu*, /Yc*, /Fp*]"));
    }
}
